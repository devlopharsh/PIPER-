import pandas as pd
df = pd.read_csv('D:/Piper/data/raw/scada_pipeline.csv')
print('=== Duplicates ===')
print('Exact duplicates:', df.duplicated().sum())
print('Duplicate (segment_id, timestamp):', df.duplicated(subset=['segment_id', 'timestamp']).sum())
print()
print('=== Missing values ===')
print(df.isnull().sum())
print()
print('=== Timestamp parsing ===')
df['timestamp_parsed'] = pd.to_datetime(df['timestamp'], format='%m/%d/%Y %H:%M')
print('Parsed successfully:', df['timestamp_parsed'].notna().all())
print('Range:', df['timestamp_parsed'].min(), 'to', df['timestamp_parsed'].max())
print()
print('=== Target validation ===')
print('Unique target values:', sorted(df['target'].unique()))
print()
print('=== Event type vs target ===')
print(pd.crosstab(df['event_type'], df['target']))
print()
print('=== Per segment stats ===')
for seg in sorted(df['segment_id'].unique()):
    seg_df = df[df['segment_id']==seg]
    print(f'Segment {seg}: {len(seg_df)} rows, unique timestamps: {seg_df["timestamp"].nunique()}, target: {seg_df["target"].unique()}')